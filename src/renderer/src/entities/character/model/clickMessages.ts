// 랜덤으로 하나 고른다(직전과 같으면 한 번 더 뽑아 변화를 준다).
let lastIndex = -1
export const pickRandomClickMessage = (): string => {
    if (CLICK_MESSAGES.length === 0) return ''
    let index = Math.floor(Math.random() * CLICK_MESSAGES.length)
    if (index === lastIndex && CLICK_MESSAGES.length > 1) {
        index = (index + 1) % CLICK_MESSAGES.length
    }
    lastIndex = index
    return CLICK_MESSAGES[index]
}
